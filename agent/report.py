"""Render a run into a single self-contained HTML page.

Shows, for every cell: the verdict, the verbatim covenant text, the formula, the
exact transactions that fed it, the comparison, the counterfactual evidence test,
and any health or reviewer flags. No CDN, no build step -- one file you can open
or hand to a judge.

    python -m agent report                 # latest attempt
    python -m agent report try3            # a specific one
"""
import html
import json
from decimal import Decimal
from pathlib import Path

from config import ARCHIVE, WORK

RUNS = WORK / "runs"

