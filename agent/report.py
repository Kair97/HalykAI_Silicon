def esc(s):
    return html.escape(str(s))


def fmt(v, unit):
    try:
        d = Decimal(str(v))
    except Exception:
        return esc(v)
    return f"{d:,.2f}" if unit == "usd" else f"{d}"


def latest_try():
    ts = sorted(RUNS.glob("try*"), key=lambda p: int(p.name[3:]) if p.name[3:].isdigit() else 0)
    if not ts:
        raise SystemExit("no attempts yet -- run: python -m agent run")
    return ts[-1].name


def build(try_name=None):
    try_name = try_name or latest_try()
    d = RUNS / try_name
    rep = json.loads((d / "compute_report.json").read_text(encoding="utf-8"))
    meta = json.loads((d / "run_meta.json").read_text(encoding="utf-8"))
    sub = json.loads((d / "submission.json").read_text(encoding="utf-8"))
    reviews = {}
    if (d / "reviews.json").exists():
        reviews = json.loads((d / "reviews.json").read_text(encoding="utf-8"))

    key = None
    kp = ARCHIVE / "ground_truth.json"
    if kp.exists():
        gt = json.loads(kp.read_text(encoding="utf-8"))
        key = {(s, c): v for s, sc in gt["scenarios"].items()
               for c, v in sc["covenants"].items()}

    n_breach = sum(1 for s in sub["answers"].values()
                   for c in s.values() if c["status"] == "BREACH")
    n_cells = sum(len(s) for s in sub["answers"].values())

    P = [f"<!-- generated by agent/report.py -->", "<div class=wrap>",
         f"<h1>Covenant verdicts — {esc(try_name)}</h1>",
         f"<p class=sub>{n_cells} cells across {len(sub['answers'])} borrowers · "
         f"{n_breach} breach, {n_cells - n_breach} compliant</p>",
         "<div class=meta>"
         f"<span><b>team</b> {esc(sub.get('team'))}</span>"
         f"<span><b>model</b> {esc(meta.get('model') or 'rule-based only')}</span>"
         f"<span><b>LLM</b> {'on' if meta.get('llm_enabled') else 'off'}</span>"
         f"<span><b>review pass</b> {'on' if meta.get('review_pass') else 'off'}</span>"
         f"<span><b>LLM calls</b> {meta.get('llm_calls',{}).get('chat',0)}</span>"
         f"<span><b>elapsed</b> {meta.get('seconds')}s</span>"
         "</div>"]

    if key:
        got = sum(1 for (s, c), k in key.items()
                  if sub["answers"][s][c]["status"] == k["status"])
        P.append(f"<div class=meta style='margin-top:10px'><span><b>scored against "
                 f"the bundled key</b> — {got}/{len(key)} statuses correct</span></div>")

    for sid, data in rep.items():
        P.append(f"<h2>{esc(sid)}</h2>")
        P.append("<div class=grid>")
        for cl, c in sorted(data["cells"].items()):
            st_cls = "ok" if c["status"] == "COMPLIANT" else "bad"
            rows = [r for r in data["rows"]
                    if r["category"] in c.get("requires", []) or r["related_party"]]
            kmark = ""
            if key and (sid, cl) in key:
                k = key[(sid, cl)]
                same = k["status"] == c["status"]
                kmark = (f"<span class='pill {"ok" if same else "warnp"}'>"
                         f"key {esc(k['status'])} {fmt(k['actual'], c['unit'])}</span>")
            P.append(
                "<div class=card>"
                f"<div class=cellhead><b>Clause {esc(cl)}</b>"
                f"<span class='pill {st_cls}'>{esc(c['status'])}</span></div>"
                f"<div class=num>{fmt(c['actual'], c['unit'])}</div>"
                f"<div class=k>{esc(c['metric'])}</div>"
                f"<div class=k style='margin-top:6px'>test: <code>{esc(c['comparison'])}</code></div>"
                + (f"<div style='margin-top:8px'>{kmark}</div>" if kmark else ""))

            ev = c.get("evidence")
            P.append("<div class=k style='margin-top:8px'>evidence: " +
                     (f"<code>{esc(ev)}</code> — reverting this one row flips the verdict"
                      if ev else "<i>none — no single row decides it</i>") + "</div>")

            rv = reviews.get(f"{sid}/{cl}")
            if rv and not rv.get("agree", True):
                P.append(f"<div class=flag><b>reviewer flagged this</b><br>"
                         f"{esc(rv.get('concern',''))}</div>")

            P.append("<details><summary>covenant text &amp; inputs</summary>"
                     f"<blockquote>{esc(c['covenant_text'])}</blockquote>"
                     f"<div class=k>threshold <code>{esc(c['threshold'])}</code> "
                     f"({esc(c['direction'])}) · unrounded <code>{esc(c['raw'])}</code></div>")
            if rows:
                P.append("<div class=scroll><table><tr><th>txn</th><th>description</th>"
                         "<th>category</th><th class=n>amount</th></tr>")
                for r in rows:
                    tags = "".join(
                        f"<span class=tag>{t}</span>" for t, on in (
                            ("RELATED", r["related_party"]),
                            ("EXCLUDED", r["excluded"]),
                            ("ONE-OFF", r["one_off"]),
                            ("RECLASSIFIED", r["reclassified"])) if on)
                    amt = r["amount_usd"] or r["amount"] or "—"
                    if amt != "—":
                        amt = f"{Decimal(amt):,.2f}"
                        if r["currency"] != "USD" and not r["amount_usd"]:
                            amt += f" {r['currency']}"
                    P.append(f"<tr><td><code>{esc(r['txn_id'])}</code></td>"
                             f"<td>{esc(r['description'][:64])}<br>{tags}</td>"
                             f"<td><code>{esc(r['category'])}</code></td>"
                             f"<td class=n>{amt}</td></tr>")
                P.append("</table></div>")
            P.append("</details></div>")
        P.append("</div>")
        P.append("<details><summary>how this borrower's inputs were assembled</summary>"
                 "<ul class=trail>"
                 + "".join(f"<li>{esc(t)}</li>" for t in data["trail"]) + "</ul></details>")

    P.append("</div>")
    out = d / "report.html"
    out.write_text(f"<title>Covenant verdicts — {esc(try_name)}</title>"
                   f"<style>{CSS}</style>" + "\n".join(P), encoding="utf-8")
    return out


if __name__ == "__main__":
    import sys
    print(build(sys.argv[1] if len(sys.argv) > 1 else None))
